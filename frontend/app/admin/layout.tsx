import { Geist, Geist_Mono } from "next/font/google";
import { headers } from "next/headers";

import type { Metadata } from "next";
import { Toaster } from "sonner";

import { ReactQueryProvider } from "@/components/providers/react-query-provider";
import { ThemeProvider } from "@/components/providers/theme-provider";

import { AcessoSuporteProvider } from "./providers/acesso-suporte-provider";
import { AdminPermissionProvider } from "./providers/admin-permission-provider";
import { BannerProvider } from "./providers/banner-provider";
import { CaixaMensagemContadorProvider } from "./providers/caixa-mensagem-contador-provider";

import "@/app/globals.css";

const geistSans = Geist({
  variable: "--font-geist-sans",
  subsets: ["latin"],
});

const geistMono = Geist_Mono({
  variable: "--font-geist-mono",
  subsets: ["latin"],
});

export const metadata: Metadata = {
  title: "Create Next App",
  description: "Generated by create next app",
};

// A CSP tem um nonce novo a cada requisição (proxy.ts): a página não pode ser pré-renderizada.
export const dynamic = "force-dynamic";

export default async function RootLayout({
  children,
}: Readonly<{
  children: React.ReactNode;
}>) {
  // Nonce da CSP desta requisição (proxy.ts): o script do tema, do `next-themes`, precisa dele.
  const nonce = (await headers()).get("x-nonce") ?? undefined;

  return (
    <html lang="pt-BR" suppressHydrationWarning>
      <body
        className={`${geistSans.variable} ${geistMono.variable} antialiased`}
      >
        <ReactQueryProvider>
          <ThemeProvider
            nonce={nonce}
            attribute="class"
            defaultTheme="system"
            enableSystem
            disableTransitionOnChange
          >
            <AdminPermissionProvider>
              <AcessoSuporteProvider>
                <CaixaMensagemContadorProvider>
                  <BannerProvider>
                    {children}
                  </BannerProvider>
                </CaixaMensagemContadorProvider>
              </AcessoSuporteProvider>
            </AdminPermissionProvider>
            <Toaster
              position="top-right"
              richColors
              closeButton
            />
          </ThemeProvider>
        </ReactQueryProvider>
      </body>
    </html>
  );
}
